enum custom_keycodes {
    CSE = SAFE_RANGE, // Ctrl+Space+Esc
    CSC,              // Ctrl+Shift+C
    CSV,              // Ctrl+Shift+V
    MSZ,              // Meta+Shift+Z
};

void keyboard_post_init_user(void) {
    // 1. Set the mode to "Solid Color" (no animation)
    rgb_matrix_mode_noeeprom(RGB_MATRIX_SOLID_COLOR);

    // 2. Set the color to Blue
    // Parameters: Hue (0-255), Saturation (0-255), Value/Brightness (0-255)
    // Blue is ~170. Saturation 255 is vivid.
    // 268
    rgb_matrix_sethsv_noeeprom(170, 255, 255);
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case CSE:
            if (record->event.pressed) {
                register_mods(MOD_BIT(KC_LCTL));
                tap_code(KC_SPC);
                tap_code(KC_ESC);
                unregister_mods(MOD_BIT(KC_LCTL));
            }
            return false;

        case CSC:
            if (record->event.pressed) {
                register_mods(MOD_BIT(KC_LCTL));
                register_mods(MOD_BIT(KC_LSFT));
                tap_code(KC_C);
                unregister_mods(MOD_BIT(KC_LSFT));
                unregister_mods(MOD_BIT(KC_LCTL));
            }
            return false;

        case CSV:
            if (record->event.pressed) {
                register_mods(MOD_BIT(KC_LCTL));
                register_mods(MOD_BIT(KC_LSFT));
                tap_code(KC_V);
                unregister_mods(MOD_BIT(KC_LSFT));
                unregister_mods(MOD_BIT(KC_LCTL));
            }
            return false;

        case MSZ:
            if (record->event.pressed) {
                register_mods(MOD_BIT(KC_LGUI));
                register_mods(MOD_BIT(KC_LSFT));
                tap_code(KC_Z);
                unregister_mods(MOD_BIT(KC_LSFT));
                unregister_mods(MOD_BIT(KC_LGUI));
            }
            return false;
    }
    return true;
}


